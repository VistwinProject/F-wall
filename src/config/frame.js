// 線寬（viewBox 單位。viewBox 1920 對到 1920px 的投影面時，1 單位 = 1px）
// 這是「亮芯」的寬度 —— 光暈由下面的 GLOW 疊出來，不要靠加粗這條線來變亮。
export const LINE_W = 1.5

// ============================================================================
// 霓虹光暈 —— 三層高斯，疊出「細亮芯 + 貼身內暈 + 大範圍體積外暈」
// ----------------------------------------------------------------------------
// sd   = feGaussianBlur 的 stdDeviation（viewBox 單位）
// gain = 用 feComponentTransfer/feFuncA 對該層 alpha 做的線性放大
//
// 為什麼需要 gain：高斯會把能量攤開。一條 1.5 寬的線用 σ=22 模糊後峰值只剩 2.7%，
// 不放大的話外暈根本看不見。gain 是把攤掉的亮度補回來。
//
// 以 LINE_W=1.5 算出來的橫向衰減（三層 src-over 疊完，尚未算最上面那條實心亮芯）：
//   距中心   0     1     2     4     8    15    25    40    60
//   alpha   46%   44%   38%   25%   16%   8.5%  4.6%  1.7%  0.2%
// → 連續平滑、沒有台階；可見半徑約 ±38 單位（掉到 2% 以下就看不出來了）。
//
// ⚠ 濾鏡區域用整個 viewBox。σ=22 理論上要 3σ=66 的餘裕，而大框上下只有 47.5
//    （框 y 47.5→1032.5，畫布 0→1080），數學尾巴會被切掉一點點 ——
//    但可見半徑 38 < 47.5，所以看得見的部分沒有被裁。
//    要是把 halo.sd 調大到超過 ~15（3σ > 47.5），上下邊就會開始出現截斷。
// ⚠ 濾鏡一定要用 filterUnits="userSpaceOnUse"。SVG 預設的 objectBoundingBox
//    對「完美水平／垂直的 <line>」會塌成零寬高，光暈會整個消失且不報錯。
//    我們 12 條格線全是軸對齊直線，百分之百中這個雷（F-table 的 beam-bloom 已踩過）。
// ============================================================================
export const GLOW = {
  near: { sd: 2, gain: 1.0 }, // 貼著核心的內暈
  mid: { sd: 7, gain: 2.0 }, // 中距離過渡
  halo: { sd: 22, gain: 3.2 }, // 大範圍體積外暈
}
