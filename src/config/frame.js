// ============================================================================
// 霓虹光暈 —— 三層「膨脹 → 模糊 → 衰減」，疊出細亮芯 + 內暈 + 體積外暈
// ----------------------------------------------------------------------------
// dilate = feMorphology 先把線加粗多少（半徑，viewBox 單位）
// sd     = feGaussianBlur 的 stdDeviation
// slope  = feComponentTransfer 對該層 alpha 的線性「衰減」（一定 < 1）
//
// ⚠ 為什麼要先膨脹再衰減，而不是直接模糊細線再放大 ⚠
// SVG 濾鏡的中間緩衝是 8-bit，放大 alpha「不會產生新的階」，只會把既有的階攤得更開：
//   舊做法 halo = 模糊 1.5 寬的線 → 峰值 2.7% = 只有 7/255 階
//           再 ×3.2 → 變成 {0,3,6,10,13,16,19,22}，仍然只有 8 個值
//           8 個值攤在 38px 的半徑上 = 每階約 4.8px 的平台 → 就是肉眼看到的色塊
//   新做法 halo = 先 dilate 到 15.5 寬再模糊 → 峰值 33% = 85/255 階（多 12 倍精度）
//           再「衰減」到同樣的 9% → 色帶寬度降到約 1.7px
// 關鍵：衰減不掉階，放大才會。要更亮就調 slope，不要回頭去放大。
//
// 目標橫向衰減（三層 src-over 疊完，尚未算最上面那條實心亮芯）：
//   距中心   0     4     8    15    25    40
//   alpha   46%   25%   16%   8.5%  4.6%  1.7%
// 可見半徑約 ±38 單位。
//
// ⚠ 濾鏡區域用整個 viewBox。大框上下離畫布邊只有 47.5，可見半徑 38 還在裡面；
//    halo.sd 調超過約 15 之後（3σ > 47.5）上下邊就會開始截斷。
// ⚠ 濾鏡一定要 filterUnits="userSpaceOnUse"。SVG 預設的 objectBoundingBox 對
//    「完美水平／垂直的 <line>」會塌成零寬高 → 光暈整個消失且不報錯。
//    我們 12 條格線全是軸對齊直線，必中（F-table 的 beam-bloom 已踩過）。
// ============================================================================
export const GLOW = {
  near: { dilate: 0.75, sd: 2, slope: 0.53 }, // 貼著核心的內暈  峰值 ~29%
  mid: { dilate: 2.5, sd: 6, slope: 0.41 }, // 中距離過渡      峰值 ~17%
  halo: { dilate: 7, sd: 18, slope: 0.27 }, // 大範圍體積外暈  峰值 ~9%
}
