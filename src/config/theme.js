// ============================================================================
// 設計 token —— 極簡黑灰白透明（樣本版）
// ----------------------------------------------------------------------------
// 三端（F-table / F-wall / F-Ipad）共用同一組 token 名稱與數值。
// CSS 端寫在各自的 tokens.css，牆面因為是 JS 物件餵給 SVG 屬性，寫在這裡。
// 改動時三端要一起改，否則三個畫面會對不起來。
//
// 原則：
//   1. 底色一律純黑 —— 投影機的黑 = 不出光，牆上的實體展品才不會被打亮。
//   2. 層級靠「線的三階不透明度 + 陰影」表達，不靠顏色。
//   3. active 訊號 = 純白高光，不使用彩色。
// ============================================================================

// ⚠ 這裡只剩「SVG 那一層」還在用的 token。
//    所有「光」的顏色（框架格線、走線光束、彗星）都在 config/fx.js 的 FX.color，
//    背景色在 FX.bg 與 styles.css —— 之前放在這裡的 bg / frameLine / frameBg /
//    surface 系列已經被 WebGL 那一套取代，全部刪掉了。
export const COLORS = {
  // ── 線 / 邊框（分層就靠這三階）──
  // ── 線 / 邊框（分層就靠這三階）──
  line: 'rgba(255,255,255,0.10)', // 極細灰線、hairline、idle 走線
  lineStrong: 'rgba(255,255,255,0.22)', // 面板外框、分隔線
  lineActive: 'rgba(255,255,255,0.85)', // active 白高光

  // ── 文字 ──
  text: 'rgba(255,255,255,0.95)',
  text2: 'rgba(255,255,255,0.62)',
  text3: 'rgba(255,255,255,0.38)',

  // 疊在毛玻璃面板上的最暗一階。
  // 面板改成半透明之後底板亮度從 ~10 升到 ~49，text3(0.38) 的對比只剩 3.25:1（低於 AA）；
  // 0.55 拉回 5.10:1。這是「把字提亮」而不是「把玻璃調濁」—— 玻璃感不用退讓。
  // 只有面板內的設備代碼與資料列左標籤用它，其他地方仍用 text3。
  textOnGlass: 'rgba(255,255,255,0.55)',

  // ── 狀態 ──
  // 樣本階段刻意走無彩：warn / err 的語意由文字（「即將到期」/「離線」）與
  // 「圓點實心 vs 空心」承擔，不用顏色。之後想開回功能色，把下面兩行換掉即可：
  //   warn: '#f59e0b',  err: '#f43f5e',
  ok: 'rgba(255,255,255,0.95)',
  warn: 'rgba(255,255,255,0.62)',
  err: 'rgba(255,255,255,0.38)',
}

