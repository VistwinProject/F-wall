// 三端（F-table / F-wall / F-Ipad）共用同一組 token 名稱與數值。
// CSS 端寫在各自的 tokens.css，牆面因為是 JS 物件餵給 SVG 屬性，寫在這裡。
// 改動時三端要一起改，否則三個畫面會對不起來。
//
// 原則：
//   1. 底色一律純黑 —— 投影機的黑 = 不出光，牆上的實體展品才不會被打亮。
//   2. 層級靠「線的三階不透明度 + 陰影」表達，不靠顏色。
//   3. active 訊號 = 純白高光，不使用彩色。
// ============================================================================

// ⚠ 這裡只剩「SVG 那一層」還在用的 token。
