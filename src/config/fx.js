// ============================================================================
// 線寬是整組特效的主控旋鈕。
//
// 走線、家電黑塊白框、中樞圓環的粗細都由它決定，而【所有特效的尺寸都跟著等比縮放】：
// 光暈的膨脹半徑與模糊半徑、濾鏡留白、能量光帶的四層寬度、彗星光點的半徑與間距。
// 想再粗一點／細一點就只改 LINE_W 這一個數字，比例自己會跟上。
//
// K 是「相對於最初調校值（1.5）的倍率」。下面凡是寫成 `x * K` 的，x 就是當初在
// 1.5 線寬下試出來的值 —— 保留原始數字才看得出是從哪裡長出來的。
//
// ⚠ 沿路徑方向的長度（圓角半徑、光帶長度）與所有時間參數【不】跟著縮放：
//   那些跟線有多粗無關，跟著放大只會讓轉角變成大彎、光帶變成一片霧。
// ============================================================================
export const LINE_W = 3 // 走線 / 家電框 active（原 1.5）
export const LINE_W_IDLE = 2 // 家電框 / 中樞環 idle（原 1）
const K = LINE_W / 1.5

export const FX = {
  // ── 走線本體 ──────────────────────────────────────────────────────────────
  // 轉折處的圓角半徑（與家電黑塊同一個座標系：黑塊圓角 6、大框 65）。
  // ⚠ routing.js 的 roundPath 會【逐個轉角】把它夾到相鄰段的一半 ——
  //   除濕機／空氣清淨機的第一段只有 4.6 單位，不夾限的話九條線全部看不出圓角。
  corner: 18,

  // 點亮時「射向中樞」的速度（單位／秒）。長線自然跑久一點：0.17s（socket）~ 0.6s（sensor）。
  // 比彗星的 420 快很多 —— 這是接通的瞬間，不是傳輸本身。
  drawSpeed: 1400,

  // ── 能量光帶 ──────────────────────────────────────────────────────────────
  // 一段亮帶沿整條線緩慢掃過（比彗星慢一半），做出「能量湧過導線」的感覺。
  // ⚠ 這是這一版唯一「每幀重繪路徑 bbox」的成本（9 台 × 2 條）。掉幀先關這個。
  beam: {
    on: true,
    speed: 220, // 單位／秒
    // ⚠ 光帶必須「比亮芯寬」才看得見。第一版是 5.5 / 2.6 寬的白色，疊在本來就是
    //   0.95 白、1.5 寬的亮芯上 —— 白疊白等於沒疊，實測完全看不出來。
    //   要讀成「能量湧過導線」，光帶得在亮芯【外面】漲起來，也就是去撐大光暈那一圈。
    //
    // 實作是疊 N 條寬度遞減的虛線。每條 stroke 的 alpha 是平坦的，所以每一層都會留下
    // 一道硬邊 —— 層數不夠就會看成一圈一圈的同心環，而不是一團光。
    // ⚠ 線寬加倍時這件事會爆掉：原本手調的四層（22/14/8/3.5）放大成 44/28/16/7 之後，
    //   每兩圈之間的平台從 ~3.5 單位變成 ~11 單位，四道邊界就全部現形了。
    //   所以層數不能寫死，要跟著攤開的半徑一起長 —— 見下面 BEAM_LAYERS 的產生器。
    spread: 11 * K, // 最外圈的半徑（＝最寬那層的一半）
    peak: 0.35, // 疊完之後中心的累積 alpha
    steps: 12, // 層數。越多階差越小、成本線性增加
    bandMax: 200, // 最外層沿路徑的長度（不隨線寬縮放）
    bandMin: 80,
  },

  // ── 彗星（資料封包）───────────────────────────────────────────────────────
  // 九條走線一律同速。長度差 3.4 倍（socket 244、sensor 833），
  // 若改成「固定週期」就會變成短線飛快、長線慢吞吞，讀起來不像同一種東西在跑。
  speed: 420, // 單位 / 秒
  minCycle: 2.0, // 一輪最短秒數：短線不要一直發射，會很吵
  duty: 0.7, // 飛行佔一輪的比例上限，剩下的停在起點等待
  // 拖尾 = 一串沿同一條路徑、彼此落後一點點的光點。
  //
  // ⚠ 兩個都會把彗尾變成「一排跑動的圓點」的坑，都踩過了：
  //   1. 間距大於光點的亮芯直徑。0.042s × 420 ＝ 18 單位間距配 r=5.5，中間就是空的。
  //   2. 半徑收得比間距快。就算間距只有 5.9，若尾端縮到 r=1.6，後半段的亮芯直徑
  //      早就小於間距，一樣散成一顆一顆。彗尾本來也不是越後面越細，是越後面越淡 ——
  //      所以半徑只微收（6.5 → 4.2），衰減交給不透明度。
  //   3. 半徑與間距要【一起】乘 K —— 但原本 1.5 線寬下的比例（間距 4.2 / 尾端亮芯直徑 4.6）
  //      只是剛好壓線，放大成 8.4 / 9.2 之後絕對尺寸變兩倍，同樣的邊界就看得出來了。
  //      所以間距的係數也一起收緊（0.01 → 0.0075），並補顆數維持拖尾長度。
  dots: 16,
  dotGap: 0.0075 * K, // 秒（× speed ＝ 間距；必須明顯小於尾端的亮芯直徑）
  headR: 6.5 * K, // 頭的半徑
  tailR: 4.2 * K, // 尾端最後一顆的半徑
  tailFade: 1.4, // 不透明度衰減指數（越大尾巴收得越快）

  // ⚠ 呼吸／點火的「曲線」在 styles.css 的 @keyframes fx-ignite / fx-breathe。
  //   keyframes 裡的 opacity 數值一律寫死、不要換成 var()，那會讓 Chrome 放棄把
  //   opacity 動畫丟給合成器 —— 正好賠掉這個設計最想要的那一件事。
  //   （stroke-dashoffset 本來就上不了合成器，所以 fx-draw / fx-beam-run 用 var() 沒差。）
  //
  // 「時長」可以放這裡：animation-duration 寫成 inline style 不影響合成器加速。
  // 閃爍要跟呼吸的 2.4s 刻意不成倍數，兩者才永遠不會重新對齊、看起來有機。
  flickerDur: 1.6, // 秒

  // ── 光暈濾鏡 ──────────────────────────────────────────────────────────────
  // 跟框架的 GLOW 同一套手法：先 feMorphology 膨脹再模糊，最後用 feComponentTransfer
  // 「衰減」。中間緩衝是 8-bit，直接模糊細線會只剩幾個色階攤在大半徑上（＝色帶）。
  // 這裡半徑小很多，所以 near 不用膨脹就有 ~51 階；outer 膨脹後換到 ~71 階。
  //
  // dilate 與 sd 一起乘 K，峰值 alpha 就不變（峰值 ≈ 線寬 / (σ·√2π)，分子分母同時放大），
  // 所以 slope 不用動 —— 光暈的亮度不變，只是整體攤開兩倍。
  glow: {
    near: { dilate: 0, sd: 2.5 * K, slope: 0.55 },
    outer: { dilate: 2 * K, sd: 8 * K, slope: 0.3 },
  },
  // ⚠ 留白必須蓋得住 outer 的擴散（dilate + 3σ），否則光暈會被濾鏡區域切出一條直邊。
  //   LINE_W=3 時是 4 + 48 = 52，所以 40 已經不夠用了，這裡也要跟著乘 K。
  pad: 40 * K,
}

// 光暈與光點的外圈色 = 框架同色，讓走線的光跟大框的光是同一種光。
// 亮芯維持純白（theme.js 的 lineActive），所以整體是「白芯 + 淡藍外暈」。
export const FX_BLUE = '#A0D8FF'

// 九台不要同步發射 —— 用索引推出的定值，不用 Math.random（每次 render 都要一樣）。
export const phaseOf = (i) => (i * 0.37) % 1

// 能量光帶的每一層。用高斯的「累積 alpha」反推每層該疊多少，
// 而不是手動填一組數字 —— 這樣層數與攤開半徑改了，落差曲線自己會維持平滑。
//
//   目標：疊到半徑 r 時的累積 alpha C(r) = peak · exp(-r² / 2σ²)
//   反推：第 i 層自己的 alpha  a = 1 - (1 - Cᵢ) / (1 - Cᵢ₋₁)
export const BEAM_LAYERS = (() => {
  const { spread, peak, steps, bandMax, bandMin } = FX.beam
  const sigma = spread / 2.2 // 最外圈剛好落在 C ≈ 0.03（＝原本手調的最外層）
  const out = []
  let prev = 0
  for (let i = 0; i < steps; i++) {
    const r = (spread * (steps - i)) / steps
    const t = r / spread
    const C = peak * Math.exp(-(r * r) / (2 * sigma * sigma))
    out.push({
      w: 2 * r,
      o: 1 - (1 - C) / (1 - prev),
      band: bandMin + (bandMax - bandMin) * t, // 越寬的層也越長：一團光本來就又寬又長
      c: mix('#FFFFFF', '#CFE8FF', t), // 中心純白 → 外圈帶一點框架的藍
    })
    prev = C
  }
  return out
})()

function mix(a, b, t) {
  const p = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
  const [ar, ag, ab] = p(a)
  const [br, bg, bb] = p(b)
  const c = (x, y) => Math.round(x + (y - x) * t).toString(16).padStart(2, '0')
  return `#${c(ar, br)}${c(ag, bg)}${c(ab, bb)}`
}

// 拖尾每一顆的半徑與不透明度：頭最大最亮，往後線性縮小、指數變淡。
// ⚠ lag 要「頭最大、尾最小」：begin="-Xs" 代表這顆在 X 秒前就出發了，X 越大跑得越前面。
//    寫成 i * dotGap 會讓 i=0（最大最亮那顆）落在最後面 —— 拖尾就會頭尾顛倒。
export const DOTS = Array.from({ length: FX.dots }, (_, i) => {
  const t = i / (FX.dots - 1)
  return {
    r: FX.headR + (FX.tailR - FX.headR) * t,
    o: Math.pow(1 - i / FX.dots, FX.tailFade),
    lag: (FX.dots - 1 - i) * FX.dotGap,
  }
})
